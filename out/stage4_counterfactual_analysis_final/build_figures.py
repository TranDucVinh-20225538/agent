#!/usr/bin/env python3
"""Figures for Paper 1 canonical audit, built from paired_results.csv / statistical_summary.json
already generated by build_final.py in this same directory. Read-only against everything else.
"""
import csv, json
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(".").resolve()
OUT = ROOT / "out" / "stage4_counterfactual_analysis_final"

paired = list(csv.DictReader(open(OUT / "paired_results.csv")))
summary = json.loads((OUT / "statistical_summary.json").read_text())

CLASS_COLOR = {"type_a": "#2a6f4f", "sensitive": "#c98a1b", "type_b": "#b3392f"}
CLASS_LABEL = {"type_a": "Type A (tracked, invariant)", "sensitive": "score-sensitive (tracked, score moves)",
               "type_b": "Type B (incomplete tracking)"}
MODEL_ORDER = ["Claude", "GPT", "Qwen3.5-35B-A3B", "Qwen3.5-9B", "Qwen3.8-Flash"]

# ---------------------------------------------------------------------------
# score_pairs_primary.png -- base vs cf score, one point per valid pair, primary tier
# ---------------------------------------------------------------------------
def score_pairs_fig(models, fname, title):
    fig, ax = plt.subplots(figsize=(5.2, 5.0))
    seen = set()
    for r in paired:
        if r["model"] not in models:
            continue
        b, c = float(r["base_score"]), float(r["cf_score"])
        clazz = r["classification"]
        lbl = CLASS_LABEL[clazz] if clazz not in seen else None
        seen.add(clazz)
        ax.scatter(b, c, color=CLASS_COLOR[clazz], s=70, zorder=3, label=lbl,
                   edgecolor="black", linewidth=0.4)
    ax.plot([0, 100], [0, 100], color="gray", linestyle="--", linewidth=1, zorder=1,
            label="score invariance (base=cf)")
    ax.set_xlim(-5, 105)
    ax.set_ylim(-5, 105)
    ax.set_xlabel("base-episode score $S^0$")
    ax.set_ylabel("counterfactual-episode score $S^1$")
    ax.set_title(title)
    ax.legend(loc="lower right", fontsize=7.5, framealpha=0.9)
    ax.set_aspect("equal")
    fig.tight_layout()
    fig.savefig(OUT / fname, dpi=200)
    plt.close(fig)

score_pairs_fig(["Claude", "GPT", "Qwen3.5-35B-A3B"], "score_pairs_primary.png",
                 "Primary tier: base vs. counterfactual score\n(Claude, GPT, Qwen3.5-35B-A3B)")
score_pairs_fig(["Qwen3.5-9B", "Qwen3.8-Flash"], "score_pairs_ablation.png",
                 "Size ablation + exploratory: base vs. counterfactual score\n(Qwen3.5-9B, Qwen3.8-Flash)")

# ---------------------------------------------------------------------------
# invariance_by_tier.png -- per-model invariance rate with Clopper-Pearson CI
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(6.4, 4.2))
xs = list(range(len(MODEL_ORDER)))
rates, los, his, ns = [], [], [], []
for m in MODEL_ORDER:
    s = summary["per_model"][m]
    r = s["invariance_rate"]
    ci = s["clopper_pearson_95ci"]
    rates.append(r if r is not None else 0.0)
    los.append((r - ci[0]) if r is not None else 0.0)
    his.append((ci[1] - r) if r is not None else 0.0)
    ns.append(s["tracking_valid"])
bars = ax.bar(xs, rates, yerr=[los, his], capsize=4, color="#3b6ea5", zorder=3)
for x, r, n in zip(xs, rates, ns):
    ax.text(x, min(r + 0.06, 0.97), f"n={n}", ha="center", fontsize=8)
ax.set_xticks(xs)
ax.set_xticklabels(MODEL_ORDER, rotation=20, ha="right", fontsize=8)
ax.set_ylabel("invariance rate among tracking-valid pairs\n(Type A / (Type A + score-sensitive))")
ax.set_ylim(0, 1.15)
ax.set_title("Score invariance rate by model, 95% Clopper--Pearson CI\n(per-model; not pooled across models)")
fig.tight_layout()
fig.savefig(OUT / "invariance_by_tier.png", dpi=200)
plt.close(fig)

# ---------------------------------------------------------------------------
# gold_state_change.png -- classification composition per model (stacked bar)
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(6.4, 4.2))
bottom = [0.0] * len(MODEL_ORDER)
for clazz in ["type_a", "sensitive", "type_b"]:
    vals = []
    for m in MODEL_ORDER:
        s = summary["per_model"][m]
        vals.append({"type_a": s["type_a"], "sensitive": s["sensitive"], "type_b": s["type_b"]}[clazz])
    ax.bar(xs, vals, bottom=bottom, color=CLASS_COLOR[clazz], label=CLASS_LABEL[clazz], zorder=3)
    bottom = [b + v for b, v in zip(bottom, vals)]
ax.set_xticks(xs)
ax.set_xticklabels(MODEL_ORDER, rotation=20, ha="right", fontsize=8)
ax.set_ylabel("valid pairs (count)")
ax.set_title("Classification of valid pairs by model\n(execution failures excluded; see failure_audit.csv)")
ax.legend(loc="upper right", fontsize=7.5, framealpha=0.9)
fig.tight_layout()
fig.savefig(OUT / "gold_state_change.png", dpi=200)
plt.close(fig)

print("figures written:", ["score_pairs_primary.png", "score_pairs_ablation.png",
                            "invariance_by_tier.png", "gold_state_change.png"])
